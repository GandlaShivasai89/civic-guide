export function getLocalizedTitle(service, lang) {
  if (!service) return '';
  if (lang !== 'en' && SERVICE_TRANSLATIONS[service.id]?.[lang]?.title) {
    return SERVICE_TRANSLATIONS[service.id][lang].title;
  }
  return service.title;
}

